def jadval(df, ustun_kengliklari=None, olcham=9.5, sarlavhalar=None):
    ncol = df.shape[1]
    t = doc.add_table(rows=1, cols=ncol)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    # Word устун кенгликларини ҳурмат қилиши учун қатъий макет режими
    tblPr = t._tbl.tblPr
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    tblPr.append(layout)

    if ustun_kengliklari is None:
        ustun_kengliklari = [USABLE.cm / ncol] * ncol

    bosh = t.rows[0].cells
    nomlar = sarlavhalar if sarlavhalar else list(df.columns)
    for j, nom in enumerate(nomlar):
        bosh[j].text = ""
        p = bosh[j].paragraphs[0]
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.space_after = Pt(2)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(str(nom))
        r.bold = True
        r.font.size = Pt(olcham)
        r.font.name = SHRIFT
        # сарлавҳа фони
        sh = OxmlElement("w:shd")
        sh.set(qn("w:val"), "clear")
        sh.set(qn("w:fill"), "DCE6F1")
        bosh[j]._tc.get_or_add_tcPr().append(sh)

    # сарлавҳа қатори ҳар бир саҳифада такрорлансин
    trPr = t.rows[0]._tr.get_or_add_trPr()
    th = OxmlElement("w:tblHeader")
    th.set(qn("w:val"), "true")
    trPr.append(th)

    for _, qator in df.iterrows():
        hujayralar = t.add_row().cells
        for j, qiy in enumerate(qator):
            hujayralar[j].text = ""
            p = hujayralar[j].paragraphs[0]
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.space_after = Pt(1)
            p.alignment = (WD_ALIGN_PARAGRAPH.LEFT if j == 0
                           else WD_ALIGN_PARAGRAPH.CENTER)
            r = p.add_run(str(qiy))
            r.font.size = Pt(olcham)
            r.font.name = SHRIFT

    # Кенгликни ҳам tblGrid (устун), ҳам ҳар бир ҳужайра даражасида белгилаш —
    # Word фақат иккиси мос келгандагина уларни ҳурмат қилади
    for j, kengl in enumerate(ustun_kengliklari):
        t.columns[j].width = Cm(kengl)
    for qator in t.rows:
        for j, hujayra in enumerate(qator.cells):
            hujayra.width = Cm(ustun_kengliklari[j])
    return t


