def matn(txt, bold=False, kursiv=False, olcham=12, chekin=True,
         tekislash=WD_ALIGN_PARAGRAPH.JUSTIFY, oldin=0, keyin=6):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(1.0 if chekin else 0)
    p.paragraph_format.alignment = tekislash
    p.paragraph_format.space_before = Pt(oldin)
    p.paragraph_format.space_after = Pt(keyin)
    r = p.add_run(txt)
    r.bold, r.italic = bold, kursiv
    r.font.size = Pt(olcham)
    r.font.name = SHRIFT
    return p


