def sahifa_raqami(section):
    p = section.footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    r = p.add_run()
    r.font.name = SHRIFT
    r.font.size = Pt(10)
    for el, atr in ((("w:fldChar"), {"w:fldCharType": "begin"}),
                    (("w:instrText"), None),
                    (("w:fldChar"), {"w:fldCharType": "end"})):
        e = OxmlElement(el)
        if el == "w:instrText":
            e.set(qn("xml:space"), "preserve")
            e.text = " PAGE "
        else:
            for k, v in atr.items():
                e.set(qn(k), v)
        r._r.append(e)


