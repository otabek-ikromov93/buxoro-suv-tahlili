def s(x, kasr=0):
    """Разрядларни бўшлиқ, ўнли касрни вергул билан: 4 027,3"""
    return f"{x:,.{kasr}f}".replace(",", " ").replace(".", ",")


def d(x, kasr=1, ishora=False):
    """Ўнли касрни вергул билан форматлаш: 0,238 ; +1,96"""
    shakl = f"{{:{'+' if ishora else ''}.{kasr}f}}"
    return shakl.format(x).replace(".", ",")


